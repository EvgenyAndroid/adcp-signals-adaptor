#!/usr/bin/env node
// scripts/vendor-request-signing-vectors.mjs
//
// Vendors the AdCP 3.2 request-signing conformance vectors (the
// `profile-3.2/{positive,negative}` tree) into one test fixture,
// tests/fixtures/request-signing-3.2.4-profile-3.2.json. The pinned
// @adcp/sdk 13.1.3 compliance cache stops at 3.2.0, which has no
// profile-3.2 directory, so tests/request-signing.test.ts cannot read these
// from node_modules the way it reads the 3.1.24 root vectors.
//
// What is copied: every vector file verbatim (parsed JSON), the sha256 of
// each file's bytes (LF line endings, i.e. the git blob), and the PUBLIC
// halves of keys.json. The `_private_d_for_test_only` members of keys.json
// are dropped — the vectors carry signatures, never private keys.
//
// Usage (the argument is a compliance bundle root holding test-vectors/):
//   node scripts/vendor-request-signing-vectors.mjs <dir>/compliance/3.2.4
// e.g. an adcp checkout's dist/compliance/3.2.4, or the 3.2.4 directory of
// a newer @adcp/sdk's compliance/cache (15.9.1 ships it; both are
// byte-identical to adcp main dist/compliance/3.2.4 at the time of writing).

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(REPO_ROOT, "tests/fixtures/request-signing-3.2.4-profile-3.2.json");

const bundleDir = process.argv[2];
if (!bundleDir) {
  console.error("usage: node scripts/vendor-request-signing-vectors.mjs <compliance-bundle-dir>");
  process.exit(1);
}
const bundle = basename(bundleDir.replace(/[\\/]+$/, ""));
if (bundle !== "3.2.4") {
  console.error(`expected a 3.2.4 bundle directory, got ${bundle}`);
  process.exit(1);
}
const root = join(bundleDir, "test-vectors/request-signing");

/** File text with CRLF folded to LF, so a Windows checkout hashes like the git blob. */
const readLf = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const sha256 = (text) => createHash("sha256").update(text, "utf8").digest("hex");

const keys = JSON.parse(readLf(join(root, "keys.json"))).keys.map((k) => {
  const { _private_d_for_test_only: _d, ...pub } = k;
  return pub;
});

const vectors = {};
for (const kind of ["positive", "negative"]) {
  for (const f of readdirSync(join(root, "profile-3.2", kind)).filter((n) => n.endsWith(".json")).sort()) {
    const text = readLf(join(root, "profile-3.2", kind, f));
    vectors[`${kind}/${f}`] = { sha256: sha256(text), vector: JSON.parse(text) };
  }
}

const fixture = {
  $comment:
    "Generated by scripts/vendor-request-signing-vectors.mjs; do not hand-edit. AdCP request-signing " +
    "conformance vectors, profile-3.2, verbatim, with public test keys only.",
  source: {
    bundle,
    path: "test-vectors/request-signing/profile-3.2",
    canonical_url: `https://adcontextprotocol.org/compliance/${bundle}/test-vectors/request-signing/`,
  },
  keys,
  vectors,
};
writeFileSync(OUT, JSON.stringify(fixture, null, 2) + "\n");
console.log(`wrote ${Object.keys(vectors).length} vectors and ${keys.length} public keys to ${OUT}`);
