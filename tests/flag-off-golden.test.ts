function makeKv() {
  const store = new Map<string, { value: string; ttl: number | null }>();
  const kv = {
    async get(k: string, type?: string) {
      const e = store.get(k);
      if (e === undefined) return null;
      return type === "json" ? JSON.parse(e.value) : e.value;
    },
    async put(k: string, v: string, opts?: { expirationTtl?: number }) {
      store.set(k, { value: v, ttl: opts?.expirationTtl ?? null });
    },
    async delete(k: string) { store.delete(k); },
    async list() { return { keys: [...store.keys()].map((name) => ({ name })), list_complete: true } as never; },
    async getWithMetadata() { return { value: null, metadata: null } as never; },
  } as unknown as KVNamespace;
  return { kv, store };
}

/** Replay-table statements run on SQLite; every other statement reads as empty. */
function makeD1() {
  const sqlite = new DatabaseSync(":memory:");
  sqlite.exec(readFileSync(MIGRATION, "utf8"));
  const db = {
    prepare(sql: string) {
      const real = sql.includes("request_signing_replay");
      let args: Array<string | number> = [];
      const stmt = {
        bind(...a: Array<string | number>) { args = a; return stmt; },
        async first() { return real ? sqlite.prepare(sql).get(...args) ?? null : null; },
        async all() { return { results: real ? sqlite.prepare(sql).all(...args) : [] }; },
        async run() {
          return { success: true, meta: { changes: real ? Number(sqlite.prepare(sql).run(...args).changes) : 0 } };
        },
      };
      return stmt;
    },
    async batch() { return []; },
  } as unknown as D1Database;
  const replayRows = () => Number((sqlite.prepare("SELECT COUNT(*) AS c FROM request_signing_replay").get() as { c: number }).c);
  return { db, replayRows };
}

