async function mcp(env: Env, rpc: unknown, bearer: string | null = KEY): Promise<unknown> {
  const headers = new Headers({ "Content-Type": "application/json" });
  if (bearer) headers.set("Authorization", `Bearer ${bearer}`);
  const res = await handleMcpRequest(new Request("https://example.com/mcp", { method: "POST", headers, body: JSON.stringify(rpc) }), env, logger);
  const text = await res.text();
  return {
    http: res.status,
    ...(res.headers.get("WWW-Authenticate") ? { www_authenticate: res.headers.get("WWW-Authenticate") } : {}),
    body: text ? foldContentText(JSON.parse(text)) : null,
  };
}

async function signed(flags: Record<string, string>, v: SignedVector): Promise<unknown> {
  vi.setSystemTime(v.reference_now * 1000);
  const { env, d1 } = makeEnv(flags);
  const res = await handleMcpRequest(
    new Request(v.request.url, { method: v.request.method, headers: v.request.headers, body: v.request.body }),
    env,
    logger,
  );
  const text = await res.text();
  vi.setSystemTime(GOLDEN_NOW);
  return {
    http: res.status,
    ...(res.headers.get("WWW-Authenticate") ? { www_authenticate: res.headers.get("WWW-Authenticate") } : {}),
    body: text ? JSON.parse(text) : null,
    replay_rows: d1.replayRows(),
  };
}

const ctx = {
  waitUntil(p: Promise<unknown>) { void p.catch(() => {}); },
  passThroughOnException() {},
} as unknown as ExecutionContext;

async function rest(env: Env, path: string, bearer: string | null): Promise<{ http: number; headers: Record<string, string>; body: Record<string, unknown> | null }> {
  const res = await worker.fetch(
    new Request(`https://adcp.signal-stack.io${path}`, { headers: bearer ? { Authorization: `Bearer ${bearer}` } : {} }),
    env,
    ctx,
  );
  const headers: Record<string, string> = {};
  for (const [k, v] of [...res.headers.entries()].sort(([a], [b]) => (a < b ? -1 : 1))) headers[k] = v;
  const text = await res.text();
  return { http: res.status, headers, body: text ? JSON.parse(text) as Record<string, unknown> : null };
}

function summariseKv(store: Map<string, { value: string; ttl: number | null }>): Record<string, unknown> {
  // Trace keys are st_<time>_<counter>: list them in write order as sigtrace:#1, #2, ...
  const traceSeq = (k: string) => parseInt(k.split("_").pop() ?? "", 36);
  const traceKeys = [...store.keys()].filter((k) => /^sigtrace:st_/.test(k)).sort((a, b) => traceSeq(a) - traceSeq(b));
  const label = (k: string) => (traceKeys.includes(k) ? `sigtrace:#${traceKeys.indexOf(k) + 1}` : normString(k));
  const out: Record<string, unknown> = {};
  for (const k of [...store.keys()].sort((a, b) => (label(a) < label(b) ? -1 : 1))) {
    const { value, ttl } = store.get(k)!;
    let parsed: unknown;
    try { parsed = JSON.parse(value); } catch { parsed = value; }
    if (k.startsWith("adcp_capabilities_")) {
      // The cached capabilities blob is the get_adcp_capabilities body pinned above.
      parsed = { sha256: createHash("sha256").update(value).digest("hex") };
    } else if (k === "sigtrace:index") {
      parsed = { entries: Array.isArray(parsed) ? parsed.length : null };
    } else if (k.startsWith("sigtrace:")) {
      const t = parsed as { tool_name?: string; response?: { payload?: { adcp_version?: unknown; status?: unknown } } };
      parsed = { tool_name: t.tool_name, response_adcp_version: t.response?.payload?.adcp_version, response_status: t.response?.payload?.status };
    }
    out[label(k)] = { ttl, value: norm(parsed) };
  }
  return out;
}

