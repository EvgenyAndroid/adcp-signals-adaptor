/** Entries as a JSON document, deduplicating any output identical to an earlier one. */
function goldenDocument(entries: Entry[]): string {
  const seen = new Map<string, string>();
  const doc: Record<string, unknown> = {};
  for (const { name, output } of entries) {
    const key = JSON.stringify(output);
    const prior = seen.get(key);
    doc[name] = prior !== undefined ? { same_as: prior } : output;
    if (prior === undefined) seen.set(key, name);
  }
  return JSON.stringify(doc, null, 2) + "\n";
}

